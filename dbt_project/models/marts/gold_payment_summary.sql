SELECT
    p.PAYMENT_STATUS,
    pol.POLICY_TYPE,
    COUNT(DISTINCT p.PAYMENT_ID) AS TOTAL_PAYMENTS,
    SUM(p.PAYMENT_AMOUNT) AS TOTAL_PAYMENT_AMOUNT,
    AVG(p.PAYMENT_AMOUNT) AS AVG_PAYMENT_AMOUNT,
    MIN(p.PAYMENT_DATE) AS FIRST_PAYMENT_DATE,
    MAX(p.PAYMENT_DATE) AS LATEST_PAYMENT_DATE
FROM {{ ref('silver_payments') }} p
LEFT JOIN {{ ref('silver_policies') }} pol
    ON p.POLICY_ID = pol.POLICY_ID
GROUP BY
    p.PAYMENT_STATUS,
    pol.POLICY_TYPE